/* PA0 as external interrupt (falling edge, pull-up) + NVIC */
static void MX_GPIO_Init(void)
{
    GPIO_InitTypeDef GPIO_InitStruct = {0};

    __HAL_RCC_GPIOA_CLK_ENABLE();                            /* UM1850: RCC Generic Driver / RCC macros */

    GPIO_InitStruct.Pin  = GPIO_PIN_0;
    GPIO_InitStruct.Mode = GPIO_MODE_IT_FALLING;             /* button to GND -> falling edge when pressed */
    GPIO_InitStruct.Pull = GPIO_PULLUP;
    HAL_GPIO_Init(GPIOA, &GPIO_InitStruct);                  /* UM1850: HAL GPIO Generic Driver / HAL_GPIO_Init */

    /* IMPORTANT: an ISR that calls FreeRTOS "FromISR" functions must have a priority
       number >= configMAX_SYSCALL_INTERRUPT_PRIORITY (5). We use 6. */
    HAL_NVIC_SetPriority(EXTI0_IRQn, 6, 0);                  /* UM1850: HAL CORTEX Generic Driver / HAL_NVIC_SetPriority */
    HAL_NVIC_EnableIRQ(EXTI0_IRQn);                          /* UM1850: HAL CORTEX Generic Driver / HAL_NVIC_EnableIRQ */
}

